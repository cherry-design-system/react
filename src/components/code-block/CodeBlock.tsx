"use client";
import {
  forwardRef,
  useEffect,
  useRef,
  useState,
  type HTMLAttributes,
  type ReactNode,
} from "react";
import { Check, Copy, Terminal } from "lucide-react";
import { cx } from "../../utils/cx";

export interface CodeBlockProps extends Omit<
  HTMLAttributes<HTMLDivElement>,
  "children"
> {
  /** The code, as plain text (no highlighting, no HTML). */
  code: string;
  /** File name shown in the header. */
  filename?: ReactNode;
  /** Language tag shown in the header ("tsx"). */
  language?: string;
  /** Line numbers in the gutter. Defaults to true. */
  lineNumbers?: boolean;
  /** 1-based lines to highlight. */
  highlightLines?: number[];
  /** Copy button in the header. Defaults to true. */
  copyable?: boolean;
  copyLabel?: string;
  copiedLabel?: string;
  /** Header icon. Defaults to a terminal glyph; null hides it. */
  icon?: ReactNode;
}

const COPIED_MS = 2000;

/**
 * A framed code listing with a header (icon, file name, language, copy) and
 * a line-number gutter. Line numbers are generated by CSS so selecting and
 * copying the text never picks them up. No syntax highlighter: pass a
 * highlighted tree to <pre> yourself if you need one.
 */
export const CodeBlock = forwardRef<HTMLDivElement, CodeBlockProps>(
  function CodeBlock(
    {
      code,
      filename,
      language,
      lineNumbers = true,
      highlightLines,
      copyable = true,
      copyLabel = "Copy code",
      copiedLabel = "Copied",
      icon,
      className,
      ...rest
    },
    ref,
  ) {
    const [copied, setCopied] = useState(false);
    const timer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
    useEffect(() => () => clearTimeout(timer.current), []);

    const lines = code.replace(/\n$/, "").split("\n");
    const highlighted = new Set(highlightLines);
    const hasHeader = Boolean(filename || language || copyable);

    const copy = async () => {
      try {
        await navigator.clipboard.writeText(code);
      } catch {
        return;
      }
      setCopied(true);
      clearTimeout(timer.current);
      timer.current = setTimeout(() => setCopied(false), COPIED_MS);
    };

    return (
      <div
        ref={ref}
        className={cx("cherry-code-block", className)}
        data-line-numbers={lineNumbers || undefined}
        {...rest}
      >
        {hasHeader ? (
          <div className="cherry-code-block__header">
            {icon !== null ? (
              <span className="cherry-code-block__icon" aria-hidden="true">
                {icon ?? <Terminal />}
              </span>
            ) : null}
            <span className="cherry-code-block__filename">{filename}</span>
            {language ? (
              <span className="cherry-code-block__language">{language}</span>
            ) : null}
            {copyable ? (
              <button
                type="button"
                className="cherry-code-block__copy"
                aria-label={copied ? copiedLabel : copyLabel}
                data-copied={copied || undefined}
                onClick={copy}
              >
                <span key={String(copied)} className="cherry-code-block__glyph">
                  {copied ? (
                    <Check aria-hidden="true" />
                  ) : (
                    <Copy aria-hidden="true" />
                  )}
                </span>
              </button>
            ) : null}
            <span className="cherry-sr-only" aria-live="polite">
              {copied ? copiedLabel : ""}
            </span>
          </div>
        ) : null}
        <pre className="cherry-code-block__pre" tabIndex={0}>
          <code
            className="cherry-code-block__code"
            data-language={language || undefined}
          >
            {lines.map((line, index) => (
              <span
                key={index}
                className="cherry-code-block__line"
                data-highlighted={highlighted.has(index + 1) || undefined}
              >
                {line}
              </span>
            ))}
          </code>
        </pre>
      </div>
    );
  },
);
